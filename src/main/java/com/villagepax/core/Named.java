package com.villagepax.core;

/**
 * Перечисление с устойчивым строковым именем для датапаков и сохранений.
 * <p>
 * Специально не используется ванильный {@code StringIdentifiable}: у него есть
 * вложенный тип с именем {@code Codec}, и внутри перечисления, реализующего
 * этот интерфейс, короткое имя {@code Codec} разрешается в него, а не в
 * мозанговский. Свой интерфейс убирает эту ловушку сразу для всех перечислений.
 */
public interface Named {
    String id();
}
