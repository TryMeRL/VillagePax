package com.villagepax.core.culture;

import com.villagepax.core.Named;

/**
 * Черта народа — <b>зарегистрированный в коде модификатор поведения</b>,
 * который культура включает одной строкой в своём json.
 * <p>
 * Это точка расширения номер один, и устроена она так не от лени. Ветвление
 * {@code if (culture == DWARF)} по всему коду — тупик: каждый новый народ
 * добавлял бы условия в десяток мест, и через три народа никто не смог бы
 * сказать, что именно делает четвёртый. Черта, наоборот, живёт в одном
 * месте и обслуживает любое число культур: гномы и дворфы-соседи включают
 * {@code builds_underground} одинаковой строкой.
 * <p>
 * Черта не может быть данными целиком. Данные умеют назвать число, но не
 * умеют объяснить движку, что «планировщик ищет площадку в горе». Поэтому
 * список здесь закрытый, а датапак — <b>включатель</b>, не автор.
 * <p>
 * <b>Чего здесь нет и почему.</b> Дизайн-документ называет ещё две
 * черты: выпас и зависимость от реки. Ни одна не объявлена здесь,
 * и это осознанно: черта без народа, который её носит, — код, который
 * никто никогда не выполнял. Каждая приедет вместе со своим народом
 * и вместе со своим тестом — так приехало {@code terrace_farming}
 * с майя, {@code builds_underground} с гномами и {@code builds_in_canopy}
 * с эльфами.
 * <p>
 * Пятая, {@code mounted_warfare}, была объявлена у норманнов и
 * <b>убрана из культуры</b>: военной системы в моде нет, а строчка
 * в датапаке, которая ничего не включает, — та же заглушка, только
 * незаметная.
 */
public enum Trait implements Named {

    /**
     * Каменное дело: с камнем работают быстро.
     * <p>
     * Норманны строят из камня и торгуют камнем — цоколь, стены, мостовая.
     * Черта делает это видимым: на каменном шаге билдер кладёт два блока
     * за решение вместо одного, и стена растёт заметно быстрее деревянной
     * пристройки рядом.
     * <p>
     * <b>Минуса по дереву нет</b>, хотя в дизайн-документе он назван. Билдер
     * и так кладёт один блок за решение, и «медленнее» означало бы стоять
     * через ход — а стоящий без дела работник это ровно то зависание, на
     * которое игрок жаловался дважды. Цена черты берётся с другой стороны:
     * камня у народа много и он дёшев, дерево норманны покупают.
     */
    STONE_MASONRY("stone_masonry"),

    /**
     * Террасное земледелие: строят на склоне.
     * <p>
     * У майя поле идёт двумя уровнями с подпорной стеной между ними — это
     * видно в самой схеме фермы. А черта делает из этого <b>умение</b>:
     * деревня, которая умеет держать землю стеной, ставит здания там, где
     * норманны сочли бы место негодным. Отсюда и разница в облике деревень:
     * норманнская стоит на ровном, майяская лепится по склону.
     */
    TERRACE_FARMING("terrace_farming"),

    /**
     * Строят в горе: поселение — чертог, вырубленный в камне.
     * <p>
     * Самая крупная из черт, и нарочно: остальные меняют <b>как</b> народ
     * строит, эта — <b>где он живёт</b>. Поселение с ней ищет место
     * не на лугу, а в толще; ставит все здания на одну отметку пола;
     * ведёт между ними вырубленные галереи вместо мощёных улиц; и прорубает
     * от ратуши ворота к дневному свету, иначе внутрь не попасть.
     * <p>
     * Правил у неё при этом одно — «пол чертога один на всё поселение»,
     * — и всё перечисленное из него следует. См. {@code Hold}.
     * <p>
     * Стены рубить движку не понадобилось учить: воздух в схеме и так
     * означает «здесь должно стать пусто, даже если сейчас гора». Гномий
     * зал — это комната с каменными стенами и пустой серединой, и билдер
     * выбивает камень теми же шагами расчистки, какими на лугу валит дерево.
     */
    BUILDS_UNDERGROUND("builds_underground"),

    /**
     * Строят в кронах: поселение поднято над лесом и связано мостами.
     * <p>
     * Зеркало подземной застройки, и написана она нарочно как зеркало.
     * У гномов пол вырублен <b>в</b> толще, у эльфов настлан <b>над</b> ней;
     * у гномов годность места решает свод над головой, у эльфов — лес
     * под настилом; гномы прорубают ход наружу, эльфы спускают лестницу
     * вниз. Общее у них одно и главное — отметка пола едина на всё
     * поселение, и обе черты отвечают на этот вопрос через одну дверь
     * ({@code Footing}).
     * <p>
     * Пара черт-зеркал — лучшая проверка, какая у тезиса «народ задаётся
     * данными» вообще может быть: если одно и то же место кода умеет
     * и закапывать деревню, и подвешивать её, то оно точно не знает
     * слов «гномы» и «эльфы».
     * <p>
     * И одно следствие пришло из чужой правки: дом в кронах — это дом
     * на весу, а площадка ещё две недели назад научилась «равнять склон,
     * а не строить сваи». Правило писалось про помосты, а пригодилось
     * здесь.
     */
    BUILDS_IN_CANOPY("builds_in_canopy");

    private final String id;

    Trait(String id) {
        this.id = id;
    }

    @Override
    public String id() {
        return id;
    }
}
