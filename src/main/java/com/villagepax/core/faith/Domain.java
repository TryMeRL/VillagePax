package com.villagepax.core.faith;

import com.mojang.serialization.Codec;
import com.villagepax.core.EnumCodecs;
import com.villagepax.core.Named;

/**
 * Домен бога — <b>зарегистрированный в коде набор действий</b>, который
 * датапак выбирает одной строкой.
 * <p>
 * Устроено по тому же правилу, что и черта народа, и по той же причине.
 * Данные умеют назвать число и предмет, но не умеют объяснить движку, что
 * «билдер кладёт на блок больше за решение» или «в отряде на бойца меньше».
 * Значит, список здесь закрытый, а датапак — <b>выбирающий</b>, не автор.
 * <p>
 * Доменов ровно три, и это не случайное число: у колонии ровно три беды,
 * которые игрок ощущает как беды, — поле не кормит, стена растёт медленно,
 * из леса приходят с оружием. Бог, который не решает ни одной из них,
 * был бы украшением с числом.
 * <p>
 * <b>Домен — не бог.</b> У каждого народа свои три бога, и совпадают
 * у них только домены: норманнский Сеятель и майяский Дающий дождь
 * делают одно и то же и зовутся по-разному. Так и должно быть — вся
 * архитектура мода стоит на том, что новый народ добавляется данными.
 */
public enum Domain implements Named {

    /**
     * Урожай: поле родит.
     * <p>
     * Благословение доращивает посевы на полях колонии каждое утро,
     * чудо — проливает дождь на весь мир.
     */
    HARVEST("harvest"),

    /**
     * Камень: стена растёт.
     * <p>
     * Благословение прибавляет билдеру блок за решение — ту же прибавку,
     * что даёт норманнам их каменное дело, и она складывается с ней:
     * народ, который умеет с камнем, под рукой своего бога кладёт втрое.
     */
    STONE("stone"),

    /**
     * Дозор: с оружием приходит меньше.
     * <p>
     * Благословение убавляет пришедший отряд на бойца — как сторожевая
     * башня, и по тому же правилу никогда не до нуля. Чудо бьёт тех,
     * кто уже стоит у ворот.
     */
    WATCH("watch");

    public static final Codec<Domain> CODEC = EnumCodecs.of(values(), "домен бога");

    private final String id;

    Domain(String id) {
        this.id = id;
    }

    @Override
    public String id() {
        return id;
    }

    /** Ключ перевода названия домена: им подписаны благословение и чудо. */
    public String key() {
        return "villagepax.faith.domain." + id;
    }
}
