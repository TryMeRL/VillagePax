package com.villagepax.entity;

/**
 * Телосложение народа: рост, ширина и голова — из одного числа.
 * <p>
 * Жалоба заказчика: «гномы обычного роста не вкатывает». Она справедлива
 * и глубже, чем звучит. Мод уже умеет отличать народы кладкой, кровлей,
 * одеждой и укладом — а люди у всех пяти были одного силуэта. Народ,
 * который живёт в горе, и народ, который живёт в кронах, нельзя было
 * различить со спины.
 *
 * <h2>Одно число, а не три</h2>
 * Датапак объявляет <b>рост</b>, и только его. Ширина и голова считаются
 * здесь, и это не лень: народ с крошечной головой на широком туловище
 * читается как ошибка отрисовки, а не как замысел, — а дав автору
 * датапака три ползунка, мы даём ему и три способа так ошибиться.
 * <p>
 * Правило простое и взято у того, как рисуют коротышек испокон веку:
 * <b>кто ниже, тот шире и головастее</b>. Гном ростом в три четверти
 * человека выходит заметно кряжистее и с крупной головой; эльф, чуть
 * выше человека, — тоньше и мельче лицом. Оба узнаются силуэтом
 * с другого конца улицы, а это и есть вся задача.
 *
 * <h2>Почему не трогаются ноги отдельно</h2>
 * Короткие ноги при обычном туловище — самый сильный признак коротышки,
 * и сделать его напрашивается. Нельзя: кость ноги вращается и тянется
 * от <b>бедра</b>, и укоротив её, мы подняли бы ступни над землёй.
 * Житель пошёл бы по воздуху в полблока — цена приметы, которую всё
 * равно видно только сбоку.
 */
public record Stature(float height, float girth, float head) {

    /** Человеческое сложение: всё по единице. */
    public static final Stature PLAIN = new Stature(1.0f, 1.0f, 1.0f);

    /**
     * Насколько сильно недобор роста уходит в ширину.
     * <p>
     * Восемь десятых: гном в 0.72 роста выходит шире человека почти
     * на четверть. Меньше — и он читается просто маленьким человеком,
     * больше — бочонком.
     */
    private static final float GIRTH_PER_HEIGHT = 0.8f;

    /** И насколько — в голову. Половина: голова растёт заметно, но не в тыкву. */
    private static final float HEAD_PER_HEIGHT = 0.5f;

    /**
     * Сложение народа такого роста.
     *
     * @param stature рост: единица — человеческий, меньше — приземистый
     */
    public static Stature of(float stature) {
        if (!(stature > 0) || stature == PLAIN.height()) {
            // Ноль, отрицательное и «не число» приходят из кривого датапака
            // и из ещё не полученного с сервера поля. Человек в этот миг —
            // единственный честный ответ.
            return PLAIN;
        }
        float shortfall = PLAIN.height() - stature;
        return new Stature(stature,
                PLAIN.girth() + shortfall * GIRTH_PER_HEIGHT,
                PLAIN.head() + shortfall * HEAD_PER_HEIGHT);
    }
}
