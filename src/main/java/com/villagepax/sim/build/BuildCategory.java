package com.villagepax.sim.build;

import com.villagepax.core.Named;

/**
 * Что за шаг делает билдер и в каком направлении идёт по слоям.
 * <p>
 * Дизайн-документ описывает порядок стройки как «расчистка → фундамент →
 * стены → крыша → декор». Буквальная реализация потребовала бы
 * <b>геометрически распознать</b>, где кончается стена и начинается крыша,
 * а это невозможно сделать надёжно: у мансарды крыша и есть стена, у башни
 * стена выше крыши пристройки.
 * <p>
 * Этого и не нужно. Фундамент лежит ниже стен, крыша выше — значит обход
 * по возрастанию высоты выкладывает их в заявленном порядке сам, и ошибиться
 * классификацией нельзя, потому что классификации нет. Остаются четыре фазы
 * и направление обхода у каждой.
 * <p>
 * Порядок объявления значим: он и есть порядок фаз стройки.
 */
public enum BuildCategory implements Named {

    /**
     * Место должно стать пустым. Идёт сверху вниз: снятый снизу блок оставил
     * бы висеть верх, и площадка выглядела бы разрушенной, а не расчищенной.
     */
    CLEAR("clear", true),

    /** Несущее: цоколь, стены, крыша. Снизу вверх, как настоящая кладка. */
    STRUCTURE("structure", false),

    /**
     * Обстановка: двери, мебель, свет, ковры. Вносится в готовую коробку,
     * иначе билдер поставил бы сундук там, где ещё нет пола под ним.
     */
    DECOR("decor", false),

    /**
     * Посев — самым последним, когда лампы уже горят.
     * <p>
     * Грядка живёт светом: без него посев при первом толчке соседа
     * осыпается. Посеянная вместе со стенами, морковь гномьего поля
     * всходила в темноте — лампы вносятся обстановкой, — и осыпалась вся,
     * стоило положить рядом следующую.
     */
    SOWING("sowing", false);

    private final String id;
    private final boolean topDown;

    BuildCategory(String id, boolean topDown) {
        this.id = id;
        this.topDown = topDown;
    }

    @Override
    public String id() {
        return id;
    }

    public boolean topDown() {
        return topDown;
    }
}
