package com.villagepax.sim.life;

import com.villagepax.core.Named;

/**
 * Характер жителя: кто он, если отнять имя и ремесло.
 * <p>
 * Долг дизайн-документа с фазы 0.2: «Черты характера (ленивый, честолюбивый,
 * набожный, трус) — дёшево и сразу делает жителей различимыми». Возраст
 * и семья уже сделали из жителя человека; характер — последняя дешёвая вещь,
 * которая делает из двух пахарей одного ремесла <b>двух разных людей</b>.
 * <p>
 * <b>У каждого характера есть и цена, и прибыль.</b> Это не симметрия ради
 * симметрии: набор из одних штрафов игрок читает как налог и перестаёт
 * смотреть в характеры вовсе — они становятся строкой, которую пролистывают.
 * Ленивый — тот, кто не уйдёт из голодной колонии; честолюбивый — тот, кого
 * стоит держать, но стоит и кормить. Выбор «кому дать хороший дом» появляется
 * только тогда, когда обе стороны чего-то стоят.
 * <p>
 * <b>Ровный ничего не меняет, и это не заглушка.</b> «Обычный человек» —
 * такой же ответ на вопрос «кто это перед тобой», как и остальные четыре,
 * и он виден в пульте наравне с ними. Без ровного каждый четвёртый житель
 * колонии работал бы вполсилы и каждый четвёртый не брал бы меча: одна пятая
 * заметна, одна четверть — уже погода.
 */
public enum Nature implements Named {

    /** Просто человек. Большинство. */
    EVEN("even"),

    /** Работает вполсилы, зато терпит вдвое дольше прочих. */
    LAZY("lazy"),

    /** Годы ему не помеха, но недовольным уходит вдвое быстрее. */
    AMBITIOUS("ambitious"),

    /** Сам носит жертвы на алтарь; без храма тоскует. */
    PIOUS("pious"),

    /** Меча не возьмёт и от налётчика бежит раньше прочих. */
    COWARD("coward");

    private final String id;

    Nature(String id) {
        this.id = id;
    }

    @Override
    public String id() {
        return id;
    }

    /** Как называется. */
    public String key() {
        return "villagepax.nature." + id;
    }

    /**
     * Чем оборачивается — одной строкой.
     * <p>
     * Обязательна у каждого, включая ровного: характер, о действии которого
     * негде прочесть, игрок принимает за украшение и один раз, навсегда.
     * Это то же правило, по которому у мода есть совет в пульте.
     */
    public String whatKey() {
        return "villagepax.nature." + id + ".what";
    }
}
