package com.villagepax.sim.work;

import net.minecraft.util.Identifier;
import net.minecraft.util.math.BlockPos;

import java.util.Optional;

/**
 * Логика профессии: что житель делает и куда для этого идёт.
 * <p>
 * Разделение ровно то, что заявлено дизайн-документом. <b>Стратегия</b> —
 * {@link #tick} — вызывается раз в {@link WorkTicker#ticksPerDecision()}
 * тиков и меняет состояние работы в данных. <b>Тактика</b> — навигация —
 * живёт в цели на сущности и умеет только «дойди до точки», которую ей
 * назвала стратегия: её возвращает тот же {@link #tick}.
 * <p>
 * Почему цель, а не {@code Brain}: у ванильного селянина вся логика в тактике,
 * и памяти есть чем делиться. У нас стратегия обязана переживать выгрузку
 * чанка и потому лежит в данных, а тактике остаётся один переход. Возвращаться
 * к {@code Brain} стоит тогда, когда тактика перестанет быть одним переходом —
 * то есть с распорядком дня, где нужны активности.
 * <p>
 * Реализаций будет семь: {@code GatherJob}, {@code FarmJob}, {@code CraftJob},
 * {@code HaulJob}, {@code BuildJob}, {@code GuardJob}, {@code SocialJob}.
 * Форма интерфейса важнее первых двух: остальные лягут в неё в задаче 1.9.
 */
public interface Job {

    /**
     * Идентификатор логики: {@code villagepax:build}, {@code villagepax:haul},
     * {@code villagepax:gather}. Профессия из датапака выбирает логику по нему.
     */
    Identifier logic();

    /**
     * Один шаг стратегии: решить, взяться, донести, поработать — и сказать,
     * куда жителю идти дальше.
     * <p>
     * Цель возвращается отсюда, а не спрашивается отдельным методом,
     * намеренно. Отдельный метод считал бы то же самое второй раз: у лесоруба
     * это два обхода леса вокруг мастерской на каждое решение, в главном
     * потоке сервера. Здесь цель — естественный итог шага.
     * <p>
     * Пусто значит «идти некуда»: житель отпускает цель навигации и уходит
     * бродить, что для свободного жителя и правильно.
     */
    Optional<BlockPos> tick(WorkContext context);
}
